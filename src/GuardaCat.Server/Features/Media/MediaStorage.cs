using System.Net;
using Amazon.S3;
using Amazon.S3.Model;
using Microsoft.Extensions.Options;

namespace GuardaCat.Server.Features.Media;

public sealed class MediaOptions
{
    public string Provider { get; set; } = "S3";
    public string LocalPath { get; set; } = "App_Data/media";
    public string Bucket { get; set; } = string.Empty;
    public string Region { get; set; } = "eu-west-1";
}

public interface IMediaStorage
{
    Task PutAsync(string key, byte[] bytes, string contentType, CancellationToken ct);
    Task<byte[]?> ReadAsync(string key, CancellationToken ct);
    Task DeleteAsync(string key, CancellationToken ct);
}

public sealed class LocalMediaStorage(IOptions<MediaOptions> options, IWebHostEnvironment environment) : IMediaStorage
{
    private string PathFor(string key)
    {
        // Keys are generated by the server, never derived from client filenames.
        if (!Guid.TryParseExact(key, "N", out _)) throw new InvalidOperationException("Invalid media key.");
        return Path.Combine(environment.ContentRootPath, options.Value.LocalPath, key);
    }

    public async Task PutAsync(string key, byte[] bytes, string contentType, CancellationToken ct)
    {
        var path = PathFor(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await File.WriteAllBytesAsync(path, bytes, ct);
    }

    public async Task<byte[]?> ReadAsync(string key, CancellationToken ct)
    {
        try { return await File.ReadAllBytesAsync(PathFor(key), ct); }
        catch (FileNotFoundException) { return null; }
        catch (DirectoryNotFoundException) { return null; }
    }

    public Task DeleteAsync(string key, CancellationToken ct)
    {
        ct.ThrowIfCancellationRequested();
        try { File.Delete(PathFor(key)); }
        catch (DirectoryNotFoundException) { }
        return Task.CompletedTask;
    }
}

public sealed class S3MediaStorage(IAmazonS3 s3, IOptions<MediaOptions> options) : IMediaStorage
{
    private static string Key(string key) => $"media/{key}";

    public async Task PutAsync(string key, byte[] bytes, string contentType, CancellationToken ct)
    {
        using var stream = new MemoryStream(bytes, writable: false);
        await s3.PutObjectAsync(new PutObjectRequest
        {
            BucketName = options.Value.Bucket, Key = Key(key), InputStream = stream,
            ContentType = contentType, ServerSideEncryptionMethod = ServerSideEncryptionMethod.AES256
        }, ct);
    }

    public async Task<byte[]?> ReadAsync(string key, CancellationToken ct)
    {
        try
        {
            using var response = await s3.GetObjectAsync(options.Value.Bucket, Key(key), ct);
            using var buffer = new MemoryStream();
            await response.ResponseStream.CopyToAsync(buffer, ct);
            return buffer.ToArray();
        }
        catch (AmazonS3Exception exception) when (exception.StatusCode == HttpStatusCode.NotFound) { return null; }
    }

    public async Task DeleteAsync(string key, CancellationToken ct) =>
        await s3.DeleteObjectAsync(options.Value.Bucket, Key(key), ct);
}
